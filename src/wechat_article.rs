/// Accept only public article routes on the actual Official Accounts host.
fn parse_article_url(input: &str) -> Option<reqwest::Url> {
    let mut url = reqwest::Url::parse(input).ok()?;
    if !matches!(url.scheme(), "http" | "https")
        || url.host_str() != Some("mp.weixin.qq.com")
        || !url.username().is_empty()
        || url.password().is_some()
        || url.port().is_some()
    {
        return None;
    }
    let path = url.path();
    let short = path.strip_prefix("/s/").is_some_and(|id| {
        !id.is_empty()
            && id
                .bytes()
                .all(|c| c.is_ascii_alphanumeric() || c == b'_' || c == b'-')
    });
    let query_article = path == "/s"
        && ["__biz", "mid", "idx", "sn"].iter().all(|key| {
            url.query_pairs()
                .any(|(name, value)| name == *key && !value.is_empty())
        });
    if !short && !query_article {
        return None;
    }
    url.set_scheme("https").ok()?;
    url.set_fragment(None);
    Some(url)
}

/// A copied share message can contain Chinese punctuation immediately before its link.
pub fn article_url(input: &str) -> Option<String> {
    for (start, _) in input.match_indices("http") {
        let rest = &input[start..];
        let candidate = rest
            .split(|c: char| c.is_whitespace() || "<>\"'，。；！、【】（）「」《》".contains(c))
            .next()?
            .trim_end_matches([')', ']', '}', ',', ';', '!', '.']);
        if let Some(url) = parse_article_url(&candidate.replace("&amp;", "&")) {
            return Some(url.to_string());
        }
    }
    None
}

fn image_url(input: &str) -> Option<reqwest::Url> {
    let url = reqwest::Url::parse(input).ok()?;
    let host = url.host_str()?;
    (url.scheme() == "https"
        && url.username().is_empty()
        && url.password().is_none()
        && url.port().is_none()
        && (host == "qpic.cn" || host.ends_with(".qpic.cn") || host == "mmbiz.qlogo.cn"))
        .then_some(url)
}

fn valid_ipc_source(message: &str, request_url: &str) -> bool {
    if message.len() > 4_000_000 {
        return false;
    }
    let Some(actual) = parse_article_url(request_url) else {
        return false;
    };
    if !request_url.starts_with("https://") {
        return false;
    }
    let Ok(value) = serde_json::from_str::<Value>(message) else {
        return false;
    };
    let Some(claimed) = parse_article_url(value["source"].as_str().unwrap_or_default()) else {
        return false;
    };
    actual == claimed
}

#[derive(Clone, Debug)]
pub struct Article {
    pub title: String,
    pub body: String,
    pub source: String,
    pub selected: bool,
    pub images: Vec<String>,
    pub author: String,
    pub published_at: String,
    /// Generated by this app's own WebView2 instance, never supplied by page IPC.
    pub native_pdf: Option<Arc<Vec<u8>>>,
}

impl Article {
    pub fn from_message(message: &str) -> Result<Self> {
        if message.len() > 4_000_000 {
            bail!("文章数据过大，未保存，请减少选取内容");
        }
        let value: Value = serde_json::from_str(message).context("公众号返回的数据无效")?;
        if value["kind"] != "wechat-article" {
            bail!("不是公众号文章数据");
        }
        let source = parse_article_url(value["source"].as_str().unwrap_or_default())
            .context("请在 mp.weixin.qq.com 官方文章页面获取正文")?
            .to_string();
        if value["complete"].as_bool() != Some(true) || value["incomplete"].as_bool() == Some(true)
        {
            bail!("正文尚未完整显示，请先在文章窗口完成验证、登录或阅读全文");
        }
        let body = value["body"].as_str().unwrap_or_default().trim().to_owned();
        let title = value["title"]
            .as_str()
            .unwrap_or_default()
            .trim()
            .to_owned();
        if title.is_empty() || title.chars().count() > 500 {
            bail!("未获取到有效文章标题，请等待文章加载后重试");
        }
        let entries = value["images"].as_array().context("文章配图数据缺失")?;
        if entries.len() > 300 {
            bail!("文章配图超过 300 张，本次未保存");
        }
        let mut images = Vec::new();
        for entry in entries {
            let url = image_url(entry.as_str().context("文章图片链接无效")?)
                .context("文章包含非微信官方图片来源，本次未保存")?
                .to_string();
            if !images.contains(&url) {
                images.push(url);
            }
        }
        if body.is_empty() && images.is_empty() {
            bail!("未获取到文章正文或配图，请等待加载完成后重试");
        }
        Ok(Self {
            title,
            body,
            source,
            selected: value["selected"].as_bool().unwrap_or(false),
            images,
            author: value["author"]
                .as_str()
                .unwrap_or_default()
                .trim()
                .to_owned(),
            published_at: value["published_at"]
                .as_str()
                .unwrap_or_default()
                .trim()
                .to_owned(),
            native_pdf: None,
        })
    }

    /// Attach a PDF produced at the app-controlled sibling of the IPC response path.
    /// A missing or incomplete print is a normal fallback case.
    pub fn attach_native_pdf(&mut self, path: &Path) -> Result<bool> {
        let Ok(metadata) = std::fs::metadata(path) else {
            return Ok(false);
        };
        if metadata.len() < 100 || metadata.len() > 150_000_000 {
            return Ok(false);
        }
        let bytes = std::fs::read(path).context("读取公众号原版排版 PDF 失败")?;
        if !looks_like_pdf(&bytes) {
            return Ok(false);
        }
        let bytes = remove_trailing_print_blanks(&bytes).unwrap_or(bytes);
        self.native_pdf = Some(Arc::new(bytes));
        Ok(true)
    }

    fn document_body(&self, body: &str) -> String {
        let mut metadata = Vec::new();
        if !self.author.is_empty() {
            metadata.push(format!("作者：{}", self.author));
        }
        if !self.published_at.is_empty() {
            metadata.push(format!("发布时间：{}", self.published_at));
        }
        metadata.push(format!("来源：{}", self.source));
        if self.selected {
            metadata.push("内容范围：手动选取的文字".into());
        }
        format!("{}\n\n{}", metadata.join("\n"), body)
    }

    pub fn export(&self, directory: &Path, format: crate::export::TextFormat) -> Result<PathBuf> {
        std::fs::create_dir_all(directory)?;
        let name = crate::bili::sanitize_filename(&self.title);
        if format == crate::export::TextFormat::Pdf {
            if let Some(bytes) = &self.native_pdf {
                return save_unique_pdf(directory, &format!("{name}_公众号_原版"), bytes);
            }
        }
        if self.images.is_empty() {
            if format == crate::export::TextFormat::Pdf {
                let temporary = tempfile::tempdir()?;
                let rendered = temporary.path().join("article.pdf");
                crate::export::save(
                    &rendered,
                    &self.title,
                    &self.document_body(&self.body),
                    format,
                )?;
                return save_unique_pdf(
                    directory,
                    &format!("{name}_公众号_图文"),
                    &std::fs::read(rendered)?,
                );
            }
            let path = directory.join(format!("{name}_公众号.{}", format.extension()));
            crate::export::save(&path, &self.title, &self.document_body(&self.body), format)?;
            return Ok(path);
        }
        // Keep the package private until every image and the document have succeeded.
        let folder = if format == crate::export::TextFormat::Pdf {
            tempfile::Builder::new()
                .prefix("shiwen-wechat-")
                .tempdir()?
        } else {
            tempfile::Builder::new()
                .prefix(&format!("{name}_公众号_"))
                .tempdir_in(directory)?
        };
        let client = reqwest::blocking::Client::builder()
            .timeout(std::time::Duration::from_secs(45))
            .redirect(reqwest::redirect::Policy::custom(|attempt| {
                if attempt.previous().len() < 5 && image_url(attempt.url().as_str()).is_some() {
                    attempt.follow()
                } else {
                    attempt.stop()
                }
            }))
            .build()?;
        let mut body = self.body.clone();
        for (index, url) in self.images.iter().enumerate() {
            image_url(url).context("文章配图链接无效")?;
            let response = client
                .get(url)
                .header("Referer", "https://mp.weixin.qq.com/")
                .send()?
                .error_for_status()?;
            let mut bytes = Vec::new();
            response.take(50_000_001).read_to_end(&mut bytes)?;
            if bytes.len() > 50_000_000 {
                bail!("第 {} 张配图超过 50 MB，本次未保存", index + 1);
            }
            let extension = image_extension(&bytes)
                .with_context(|| format!("第 {} 张配图未能下载为图片，本次未保存", index + 1))?;
            let filename = format!("配图{:03}.{extension}", index + 1);
            std::fs::File::create(folder.path().join(&filename))?.write_all(&bytes)?;
            // Markdown links remain useful offline beside the downloaded images.
            body = body.replace(&format!("]({url})"), &format!("]({filename})"));
        }
        let document_path = folder.path().join(format!("{name}.{}", format.extension()));
        let body = self.document_body(&body);
        if format == crate::export::TextFormat::Pdf {
            let bytes = crate::export::wechat_pdf_bytes(&self.title, &body, folder.path())?;
            return save_unique_pdf(directory, &format!("{name}_公众号_图文"), &bytes);
        } else {
            crate::export::save(&document_path, &self.title, &body, format)?;
        }
        Ok(folder.keep())
    }
}

fn save_unique_pdf(directory: &Path, stem: &str, bytes: &[u8]) -> Result<PathBuf> {
    let mut file = tempfile::NamedTempFile::new_in(directory)?;
    file.write_all(bytes)?;
    file.as_file().sync_all()?;
    for number in 1..=1000 {
        let suffix = if number == 1 {
            String::new()
        } else {
            format!("_{number}")
        };
        let path = directory.join(format!("{stem}{suffix}.pdf"));
        match file.persist_noclobber(&path) {
            Ok(_) => return Ok(path),
            Err(error) if error.error.kind() == std::io::ErrorKind::AlreadyExists => {
                file = error.file;
            }
            Err(error) => return Err(error.error).context("保存公众号 PDF 失败"),
        }
    }
    bail!("同名公众号 PDF 过多，请先整理输出目录");
}

fn looks_like_pdf(bytes: &[u8]) -> bool {
    bytes.starts_with(b"%PDF-")
        && bytes[bytes.len().saturating_sub(4_096)..]
            .windows(5)
            .any(|w| w == b"%%EOF")
}

/// Chromium occasionally appends a page containing only its white paper background.
/// Remove only such trailing pages; preserve every page with text, images, or other drawing.
fn remove_trailing_print_blanks(bytes: &[u8]) -> Option<Vec<u8>> {
    let mut document = lopdf::Document::load_mem(bytes).ok()?;
    let pages = document.get_pages();
    if pages.len() < 2 {
        return None;
    }
    let mut blank_pages = Vec::new();
    for (&number, &id) in pages.iter().rev() {
        if number == 1 {
            break;
        }
        let content = document.get_page_content(id).ok()?;
        if !is_white_print_page(&content) {
            break;
        }
        blank_pages.push(number);
    }
    if blank_pages.is_empty() {
        return None;
    }
    document.delete_pages(&blank_pages);
    document.prune_objects();
    let mut cleaned = Vec::new();
    document.save_to(&mut cleaned).ok()?;
    (looks_like_pdf(&cleaned)
        && lopdf::Document::load_mem(&cleaned).ok()?.get_pages().len()
            == pages.len() - blank_pages.len())
    .then_some(cleaned)
}

fn is_white_print_page(stream: &[u8]) -> bool {
    if stream.len() > 512 {
        return false;
    }
    let Ok(content) = lopdf::content::Content::decode(stream) else {
        return false;
    };
    let mut white = false;
    let mut rectangle = false;
    let mut fill = false;
    for operation in content.operations {
        match operation.operator.as_str() {
            "q" | "Q" | "cm" | "gs" => {}
            "RG" | "rg" => {
                if operation.operands.len() != 3
                    || !operation
                        .operands
                        .iter()
                        .all(|value| value.as_float().is_ok_and(|component| component >= 0.999))
                {
                    return false;
                }
                if operation.operator == "rg" {
                    white = true;
                }
            }
            "re" if operation.operands.len() == 4 => rectangle = true,
            "f" if operation.operands.is_empty() => fill = true,
            _ => return false,
        }
    }
    white && rectangle && fill
}

/// The child process and parent process derive this from an app-created random response path.
/// The website is never allowed to choose where a PDF is written.
pub fn native_pdf_path(response_path: &Path) -> PathBuf {
    response_path.with_extension("pdf")
}

fn image_extension(bytes: &[u8]) -> Option<&'static str> {
    if bytes.starts_with(&[0xff, 0xd8, 0xff]) {
        Some("jpg")
    } else if bytes.starts_with(b"\x89PNG\r\n\x1a\n") {
        Some("png")
    } else if bytes.starts_with(b"GIF87a") || bytes.starts_with(b"GIF89a") {
        Some("gif")
    } else if bytes.starts_with(b"RIFF") && bytes.get(8..12) == Some(b"WEBP") {
        Some("webp")
    } else if bytes.get(4..12) == Some(b"ftypavif") || bytes.get(4..12) == Some(b"ftypavis") {
        Some("avif")
    } else {
        None
    }
}

