#[cfg(windows)]
pub fn open_reader_with_pdf(input: &str, output: &Path, want_native_pdf: bool) -> Result<bool> {
    use winit::{
        application::ApplicationHandler,
        event::WindowEvent,
        event_loop::{ActiveEventLoop, ControlFlow, EventLoop, EventLoopProxy},
        window::{Window, WindowId},
    };
    enum ReaderEvent {
        Article(String),
        PdfDone(bool),
    }
    struct Reader {
        webview: Option<wry::WebView>,
        window: Option<Window>,
        url: String,
        proxy: EventLoopProxy<ReaderEvent>,
        result: Option<Result<Option<String>>>,
        want_native_pdf: bool,
        pdf_path: PathBuf,
        pending_article: Option<String>,
        print_deadline: Option<std::time::Instant>,
    }
    impl Reader {
        fn finish_pdf(&mut self, event_loop: &ActiveEventLoop, successful: bool) {
            let valid = successful
                && std::fs::metadata(&self.pdf_path)
                    .is_ok_and(|metadata| metadata.len() <= 150_000_000)
                && std::fs::read(&self.pdf_path)
                    .is_ok_and(|bytes| bytes.len() <= 150_000_000 && looks_like_pdf(&bytes));
            if !valid {
                let _ = std::fs::remove_file(&self.pdf_path);
            }
            self.print_deadline = None;
            self.result = Some(Ok(self.pending_article.take()));
            event_loop.exit();
        }
    }
    impl ApplicationHandler<ReaderEvent> for Reader {
        fn resumed(&mut self, event_loop: &ActiveEventLoop) {
            if self.window.is_some() {
                return;
            }
            let setup = (|| -> Result<_> {
                let profile =
                    crate::zhihu_login::session_directory().join("wechat-article-webview");
                std::fs::create_dir_all(&profile)?;
                let window = event_loop.create_window(
                    Window::default_attributes()
                        .with_title("拾文 · 微信公众号（正文显示完整后点击获取）")
                        .with_inner_size(winit::dpi::LogicalSize::new(1040.0, 720.0)),
                )?;
                let mut context = wry::WebContext::new(Some(profile));
                let proxy = self.proxy.clone();
                let webview = wry::WebViewBuilder::new_with_web_context(&mut context)
                    .with_initialization_script(include_str!("wechat_article_reader.js"))
                    .with_navigation_handler(|input| {
                        reqwest::Url::parse(&input).is_ok_and(|url| {
                            url.scheme() == "https"
                                && url.host_str() == Some("mp.weixin.qq.com")
                                && url.username().is_empty()
                                && url.password().is_none()
                                && url.port().is_none()
                        })
                    })
                    .with_ipc_handler(move |request| {
                        if valid_ipc_source(request.body(), &request.uri().to_string()) {
                            let _ = proxy.send_event(ReaderEvent::Article(request.body().clone()));
                        }
                    })
                    .with_url(&self.url)
                    .build(&window)
                    .context("无法打开公众号窗口，请检查 WebView2 Runtime")?;
                Ok((window, webview))
            })();
            match setup {
                Ok((window, webview)) => {
                    self.window = Some(window);
                    self.webview = Some(webview);
                }
                Err(error) => {
                    self.result = Some(Err(error));
                    event_loop.exit();
                }
            }
        }
        fn user_event(&mut self, event_loop: &ActiveEventLoop, event: ReaderEvent) {
            match event {
                ReaderEvent::Article(message) => {
                    if self.pending_article.is_some() {
                        return;
                    }
                    match Article::from_message(&message) {
                        Ok(_)
                            if self.want_native_pdf
                                && serde_json::from_str::<Value>(&message)
                                    .ok()
                                    .and_then(|value| value["print_ready"].as_bool())
                                    == Some(true) =>
                        {
                            let proxy = self.proxy.clone();
                            let print_started = self.webview.as_ref().is_some_and(|webview| {
                                native_print::start(webview, &self.pdf_path, move |success| {
                                    let _ = proxy.send_event(ReaderEvent::PdfDone(success));
                                })
                                .is_ok()
                            });
                            self.pending_article = Some(message);
                            if print_started {
                                let deadline =
                                    std::time::Instant::now() + std::time::Duration::from_secs(90);
                                self.print_deadline = Some(deadline);
                                event_loop.set_control_flow(ControlFlow::WaitUntil(deadline));
                            } else {
                                self.finish_pdf(event_loop, false);
                            }
                        }
                        Ok(_) => {
                            self.result = Some(Ok(Some(message)));
                            event_loop.exit();
                        }
                        Err(error) => {
                            rfd::MessageDialog::new()
                                .set_title("微信公众号")
                                .set_description(error.to_string())
                                .show();
                        }
                    }
                }
                ReaderEvent::PdfDone(success) if self.pending_article.is_some() => {
                    self.finish_pdf(event_loop, success);
                }
                ReaderEvent::PdfDone(_) => {}
            }
        }
        fn about_to_wait(&mut self, event_loop: &ActiveEventLoop) {
            if self
                .print_deadline
                .is_some_and(|deadline| std::time::Instant::now() >= deadline)
            {
                self.finish_pdf(event_loop, false);
            }
        }
        fn window_event(&mut self, event_loop: &ActiveEventLoop, _: WindowId, event: WindowEvent) {
            if matches!(event, WindowEvent::CloseRequested) {
                event_loop.exit();
            }
        }
    }
    let url = article_url(input).context("请粘贴微信公众号文章链接或包含链接的分享文字")?;
    let event_loop = EventLoop::<ReaderEvent>::with_user_event().build()?;
    let mut reader = Reader {
        webview: None,
        window: None,
        url,
        proxy: event_loop.create_proxy(),
        result: None,
        want_native_pdf,
        pdf_path: native_pdf_path(output),
        pending_article: None,
        print_deadline: None,
    };
    event_loop.run_app(&mut reader)?;
    match reader.result.unwrap_or(Ok(None))? {
        Some(message) => {
            std::fs::write(output, message)?;
            Ok(true)
        }
        None => Ok(false),
    }
}

