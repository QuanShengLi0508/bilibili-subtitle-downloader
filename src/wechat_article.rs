    #[test]
    fn native_pdf_requires_complete_output_and_never_overwrites_existing_export() {
        let directory = tempfile::tempdir().unwrap();
        let response = directory.path().join("reader-response.json");
        let printed = native_pdf_path(&response);
        let mut article = Article::from_message(&payload().to_string()).unwrap();
        std::fs::write(&printed, b"%PDF-1.7\nmissing trailer").unwrap();
        assert!(!article.attach_native_pdf(&printed).unwrap());

        let pdf = format!("%PDF-1.7\n{}\n%%EOF\n", "native page ".repeat(16));
        std::fs::write(&printed, pdf.as_bytes()).unwrap();
        assert!(article.attach_native_pdf(&printed).unwrap());
        let first = directory.path().join("公众号测试_公众号_原版.pdf");
        std::fs::write(&first, b"older user document").unwrap();
        let second = article
            .export(directory.path(), crate::export::TextFormat::Pdf)
            .unwrap();
        assert_eq!(std::fs::read(first).unwrap(), b"older user document");
        assert!(second.ends_with("公众号测试_公众号_原版_2.pdf"));
        assert_eq!(std::fs::read(second).unwrap(), pdf.as_bytes());
    }
