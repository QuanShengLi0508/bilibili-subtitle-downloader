const _alphabet =
    '6fpLRqJO8M/c3jnYxFkUVC4ZIG12SiH=5v0mXDazWBTsuw7QetbKdoPyAl+hN9rgE';
int _rot(int n, int bits) => ((n << bits) | (n >> (32 - bits))) & 0xffffffff;
int _read(List<int> b, int off) =>
    (b[off] << 24) | (b[off + 1] << 16) | (b[off + 2] << 8) | b[off + 3];
List<int> _block(List<int> bytes) {
  final tr = List<int>.filled(36, 0);
  for (var i = 0; i < 4; i++) {
    tr[i] = _read(bytes, i * 4);
  }
  for (var i = 0; i < 32; i++) {
    final t = tr[i + 1] ^ tr[i + 2] ^ tr[i + 3] ^ _zk[i];
    final v =
        (_zb[(t >> 24) & 255] << 24) |
        (_zb[(t >> 16) & 255] << 16) |
        (_zb[(t >> 8) & 255] << 8) |
        _zb[t & 255];
    tr[i + 4] =
        (tr[i] ^ v ^ _rot(v, 2) ^ _rot(v, 10) ^ _rot(v, 18) ^ _rot(v, 24)) &
        0xffffffff;
  }
  return [
    for (var i = 35; i >= 32; i--)
      for (final shift in [24, 16, 8, 0]) (tr[i] >> shift) & 255,
  ];
}

String encryptZse(String input) {
  final plain = [210, 0, ...ascii.encode(Uri.encodeComponent(input))];
  final pad = 16 - plain.length % 16;
  plain.addAll(List.filled(pad, pad));
  final key = ascii.encode('059053f7d15e01d7');
  var iv = _block(List.generate(16, (i) => plain[i] ^ key[i] ^ 42));
  final cipher = [...iv];
  for (var off = 16; off < plain.length; off += 16) {
    iv = _block(List.generate(16, (i) => plain[off + i] ^ iv[i]));
    cipher.addAll(iv);
  }
  while (cipher.length % 3 != 0) {
    cipher.add(0);
  }
  var counter = 0;
  final result = StringBuffer();
  for (var p = cipher.length - 1; p >= 0; p -= 3) {
    var v = 0;
    for (var j = 0; j < 3; j++) {
      v |=
          ((cipher[p - j] ^ ((58 >> (8 * (counter++ % 4))) & 255)) & 255) <<
          (j * 8);
    }
    for (final shift in [0, 6, 12, 18]) {
      result.write(_alphabet[(v >> shift) & 63]);
    }
  }
  return result.toString();
}

Map<String, String> signZhihu(String url, String cookie) {
  final uri = Uri.parse(url);
  final path = uri.path + (uri.hasQuery ? '?${uri.query}' : '');
  final digest = md5.convert(utf8.encode('101_3_3.0+$path+$cookie')).toString();
  return {
    'x-zse-93': '101_3_3.0',
    'x-zse-96': '2.0_${encryptZse(digest)}',
    'x-requested-with': 'fetch',
  };
}
